package orm

import (
	"fmt"
	"reflect"
	"sync"

	"github.com/mhdaslam790/kiln/internal/meta"
)

// ModelInfo describes how a struct maps to a table.
type ModelInfo struct {
	Name   string // Go type name
	Table  string
	Fields []FieldInfo // mapped columns, in declaration order
}

// FieldInfo describes one mapped column.
type FieldInfo struct {
	Name     string // Go field name
	Column   string
	Type     reflect.Type
	Primary  bool
	Auto     bool // generated by the database (auto-increment)
	JSON     bool // stored as JSON
	ReadOnly bool
}

// Describe returns the table and columns the ORM uses for model, which may
// be a struct value, a pointer to one, or a reflect.Type. It is what
// `kiln gen` uses to generate typed columns, and is handy for admin
// screens, validation or exports.
func Describe(model any) (ModelInfo, error) {
	t, ok := model.(reflect.Type)
	if !ok {
		t = reflect.TypeOf(model)
	}
	for t != nil && t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == nil {
		return ModelInfo{}, fmt.Errorf("orm: Describe needs a struct, got %T", model)
	}
	m, err := meta.Of(t)
	if err != nil {
		return ModelInfo{}, err
	}
	info := *modelInfo(m)
	info.Fields = append([]FieldInfo(nil), info.Fields...) // callers may modify their copy
	return info, nil
}

// Column returns the field mapped to column.
func (mi ModelInfo) Column(column string) (FieldInfo, bool) {
	for _, f := range mi.Fields {
		if f.Column == column {
			return f, true
		}
	}
	return FieldInfo{}, false
}

var modelInfos sync.Map // *meta.Model -> *ModelInfo

// modelInfo returns the (shared, read-only) description of m, or nil.
func modelInfo(m *meta.Model) *ModelInfo {
	if m == nil {
		return nil
	}
	if v, ok := modelInfos.Load(m); ok {
		return v.(*ModelInfo)
	}
	info := &ModelInfo{Name: m.Type.Name(), Table: m.Table, Fields: make([]FieldInfo, len(m.Fields))}
	for i, f := range m.Fields {
		info.Fields[i] = FieldInfo{
			Name: f.Name, Column: f.Column, Type: f.Type,
			Primary: f.Primary, Auto: f.Auto, JSON: f.JSON, ReadOnly: f.ReadOnly,
		}
	}
	v, _ := modelInfos.LoadOrStore(m, info)
	return v.(*ModelInfo)
}
