package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/mhdaslam790/kiln/internal/meta"
)

// Default directories for the layers written by Scaffold.
const (
	DefaultRepositories = "internal/repository"
	DefaultUsecases     = "internal/usecase"
)

// ScaffoldOptions configures Scaffold.
type ScaffoldOptions struct {
	Force bool // overwrite existing files
}

// Scaffold writes clean-architecture layers for an existing model:
//
//   - a repository interface (the port) next to the entity, in the models
//     package (internal/domain by default);
//   - its kiln implementation in the repositories package;
//   - a usecase that depends only on the interface.
//
// The files are a starting point meant to be edited: trim the interface
// to the methods your usecase needs and add specific ones. Existing files
// are never overwritten without Force.
func (p *Project) Scaffold(model string, o ScaffoldOptions) error {
	name := meta.Camel(meta.Snake(model))
	mf, err := p.findModel(name)
	if err != nil {
		return err
	}
	idField, _, _ := mf.findField("id")
	if idField == nil || len(idField.Names) == 0 {
		return fmt.Errorf("scaffold needs a model with an id primary key; %s has none", name)
	}
	idType := mf.exprString(idField.Type)

	repos := p.Config.Repositories
	if repos == "" {
		repos = DefaultRepositories
	}
	usecases := p.Config.Usecases
	if usecases == "" {
		usecases = DefaultUsecases
	}
	l := layerNames{
		Model: name, Lower: lowerFirst(name), IDType: idType,
		DomainPkg: lastSegment(p.Config.Models), DomainImport: p.importPath(p.Config.Models),
		RepoPkg: lastSegment(repos), UsecasePkg: lastSegment(usecases),
	}
	file := meta.Snake(name)

	type out struct {
		path, src string
		once      bool // shared helper: skip silently when present
	}
	files := []out{
		{p.path(p.Config.Models, file+"_repository.go"), l.port(), false},
		{p.path(repos, file+"_repository.go"), l.repository(), false},
		{p.path(usecases, file+"_usecase.go"), l.usecase(), false},
	}
	if !declares(p.path(p.Config.Models), errNotFoundDecl) {
		files = append([]out{{p.path(p.Config.Models, "errors.go"), l.domainErrors(), true}}, files...)
	}
	if !declares(p.path(repos), mapErrDecl) {
		files = append(files, out{p.path(repos, "errors.go"), l.repoErrors(), true})
	}

	// Check everything first so a conflict leaves no half-written layers.
	if !o.Force {
		var exist []string
		for _, f := range files {
			if _, err := os.Stat(f.path); err == nil && !f.once {
				exist = append(exist, p.rel(f.path))
			}
		}
		if len(exist) > 0 {
			return fmt.Errorf("already scaffolded (%s); use --force to overwrite your edits", strings.Join(exist, ", "))
		}
	}
	for _, f := range files {
		if err := p.writeGo(f.path, f.src, o.Force && !f.once); err != nil {
			return err
		}
		p.Out("created %s", p.rel(f.path))
	}
	p.Out("\nwire it up:\n  repo := %s.New%sRepository(db)\n  uc := %s.New%sUsecase(repo)\nthen trim %sRepository to the methods your usecase needs.",
		l.RepoPkg, name, l.UsecasePkg, name, name)
	return nil
}

var (
	errNotFoundDecl = regexp.MustCompile(`(?m)^\s*(var\s+)?ErrNotFound\s*(error\s*)?=`)
	mapErrDecl      = regexp.MustCompile(`(?m)^func mapErr\(`)
)

// declares reports whether any non-test Go file in dir matches re.
func declares(dir string, re *regexp.Regexp) bool {
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		if b, err := os.ReadFile(filepath.Join(dir, e.Name())); err == nil && re.Match(b) {
			return true
		}
	}
	return false
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	// Leading acronyms: URLRecord -> urlRecord, ID -> id.
	r := []rune(s)
	i := 0
	for i < len(r) && r[i] >= 'A' && r[i] <= 'Z' {
		i++
	}
	switch {
	case i == len(r):
		i = len(r)
	case i > 1:
		i--
	default:
		i = 1
	}
	return strings.ToLower(string(r[:i])) + string(r[i:])
}

type layerNames struct {
	Model, Lower, IDType    string
	DomainPkg, DomainImport string
	RepoPkg, UsecasePkg     string
}

func (l layerNames) port() string {
	return fmt.Sprintf(`package %[1]s

import "context"

// %[2]sRepository is the storage port for %[2]s. The usecase depends on this
// interface only; the kiln implementation lives in the %[3]s package.
//
// Generated by kiln scaffold as a starting point: keep it small and
// specific to what the usecase needs (e.g. FindByEmail), and delete
// methods nobody calls.
type %[2]sRepository interface {
	FindByID(ctx context.Context, id %[4]s) (%[2]s, error)
	List(ctx context.Context) ([]%[2]s, error)
	Create(ctx context.Context, rec *%[2]s) error
	Update(ctx context.Context, rec *%[2]s) error
	Delete(ctx context.Context, rec *%[2]s) error
}
`, l.DomainPkg, l.Model, l.RepoPkg, l.IDType)
}

func (l layerNames) repository() string {
	return fmt.Sprintf(`package %[1]s

import (
	"context"

	"github.com/mhdaslam790/kiln/orm"

	"%[2]s"
)

// %[4]sRepository stores %[3]s.%[5]s with kiln.
type %[4]sRepository struct {
	repo *orm.Repo[%[3]s.%[5]s]
}

// New%[5]sRepository returns the kiln implementation of %[3]s.%[5]sRepository.
func New%[5]sRepository(db *orm.DB) %[3]s.%[5]sRepository {
	return &%[4]sRepository{repo: orm.For[%[3]s.%[5]s](db)}
}

var _ %[3]s.%[5]sRepository = (*%[4]sRepository)(nil)

func (r *%[4]sRepository) FindByID(ctx context.Context, id %[6]s) (%[3]s.%[5]s, error) {
	rec, err := r.repo.FindByID(ctx, id)
	return rec, mapErr(err)
}

func (r *%[4]sRepository) List(ctx context.Context) ([]%[3]s.%[5]s, error) {
	return r.repo.FindAll(ctx)
}

func (r *%[4]sRepository) Create(ctx context.Context, rec *%[3]s.%[5]s) error {
	return mapErr(r.repo.Insert(ctx, rec))
}

func (r *%[4]sRepository) Update(ctx context.Context, rec *%[3]s.%[5]s) error {
	return mapErr(r.repo.Update(ctx, rec))
}

func (r *%[4]sRepository) Delete(ctx context.Context, rec *%[3]s.%[5]s) error {
	return mapErr(r.repo.Delete(ctx, rec))
}
`, l.RepoPkg, l.DomainImport, l.DomainPkg, l.Lower, l.Model, l.IDType)
}

func (l layerNames) usecase() string {
	return fmt.Sprintf(`package %[1]s

import (
	"context"

	"%[2]s"
)

// %[4]sUsecase holds the business rules for %[4]s. It depends only on the
// %[3]s.%[4]sRepository interface, so tests can pass a fake repository.
type %[4]sUsecase struct {
	repo %[3]s.%[4]sRepository
}

func New%[4]sUsecase(repo %[3]s.%[4]sRepository) *%[4]sUsecase {
	return &%[4]sUsecase{repo: repo}
}

func (uc *%[4]sUsecase) Get(ctx context.Context, id %[5]s) (%[3]s.%[4]s, error) {
	return uc.repo.FindByID(ctx, id)
}

func (uc *%[4]sUsecase) List(ctx context.Context) ([]%[3]s.%[4]s, error) {
	return uc.repo.List(ctx)
}

func (uc *%[4]sUsecase) Create(ctx context.Context, rec *%[3]s.%[4]s) error {
	// Validate and apply business rules here.
	return uc.repo.Create(ctx, rec)
}

func (uc *%[4]sUsecase) Update(ctx context.Context, rec *%[3]s.%[4]s) error {
	return uc.repo.Update(ctx, rec)
}

func (uc *%[4]sUsecase) Delete(ctx context.Context, id %[5]s) error {
	rec, err := uc.repo.FindByID(ctx, id)
	if err != nil {
		return err
	}
	return uc.repo.Delete(ctx, &rec)
}
`, l.UsecasePkg, l.DomainImport, l.DomainPkg, l.Model, l.IDType)
}

func (l layerNames) domainErrors() string {
	return fmt.Sprintf(`package %s

import "errors"

// ErrNotFound is returned by repositories when no record matches, so
// usecases never depend on the database package's errors.
var ErrNotFound = errors.New("not found")
`, l.DomainPkg)
}

func (l layerNames) repoErrors() string {
	return fmt.Sprintf(`package %[1]s

import (
	"errors"

	"github.com/mhdaslam790/kiln/orm"

	"%[2]s"
)

// mapErr translates kiln errors into domain errors.
func mapErr(err error) error {
	if errors.Is(err, orm.ErrNotFound) {
		return %[3]s.ErrNotFound
	}
	return err
}
`, l.RepoPkg, l.DomainImport, l.DomainPkg)
}
