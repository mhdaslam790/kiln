func migrationTmpl(pkg string, version int64, name string, up, down []string) string {
	body := func(lines []string) string {
		if len(lines) == 0 {
			return "\t\t\t// TODO\n"
		}
		var b strings.Builder
		for _, l := range lines {
			b.WriteString("\t\t\t" + l + "\n")
		}
		return b.String()
	}
	return fmt.Sprintf(`package %s

import "%s/schema"

func init() {
	Set.Add(%d, %q,
		func(s *schema.Schema) {
%s		},
		func(s *schema.Schema) {
%s		},
	)
}
`, pkg, libPath, version, name, body(up), body(down))
}

