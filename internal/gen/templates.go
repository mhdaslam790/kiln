func runnerTmpl(module string, cfg Config, d driverInfo) string {
	migPkg := module + "/" + strings.TrimPrefix(cfg.Migrations, "./")
	return fmt.Sprintf(`// Command migrate applies the database migrations.
//
//	DATABASE_URL=%[5]q go run ./%[6]s [up|down [n]|redo|status|sql|seed [name...]]
//
// Generated by kiln init; this file is yours to edit.
package main

import (
	"context"
	"fmt"
	"os"
	"strconv"

	_ %[1]q

	"%[7]s/dialect"
	"%[7]s/env"
	"%[7]s/migrate"
	"%[7]s/orm"

	"%[4]s"
	"%[9]s"
)

func main() {
	if err := run(context.Background(), os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, args []string) error {
	if err := env.Load(); err != nil { // .env, if present; real env vars win
		return err
	}
	dsn := os.Getenv("DATABASE_URL")
	if dsn == "" {
		return fmt.Errorf("DATABASE_URL is not set: add it to .env or export it")
	}
	db, err := orm.Connect(ctx, %[2]q, dsn, dialect.%[3]s())
	if err != nil {
		return err
	}
	defer db.Close()

	m := migrate.New(db, %[8]s.Set.List(), migrate.WithLog(func(f string, a ...any) {
		fmt.Printf(f+"\n", a...)
	}))

	cmd := "up"
	if len(args) > 0 {
		cmd = args[0]
	}
	switch cmd {
	case "up":
		applied, err := m.Up(ctx)
		if err == nil && len(applied) == 0 {
			fmt.Println("nothing to migrate")
		}
		return err
	case "down", "rollback":
		n := 1
		if len(args) > 1 {
			if n, err = strconv.Atoi(args[1]); err != nil {
				return fmt.Errorf("invalid count %%q", args[1])
			}
		}
		rolled, err := m.Down(ctx, n)
		if err == nil && len(rolled) == 0 {
			fmt.Println("nothing to roll back")
		}
		return err
	case "redo":
		return m.Redo(ctx)
	case "status":
		st, err := m.Status(ctx)
		if err != nil {
			return err
		}
		for _, s := range st {
			state := "pending"
			switch {
			case s.Missing:
				state = "MISSING FROM CODE"
			case s.Applied:
				state = "applied " + s.AppliedAt.Format("2006-01-02 15:04:05")
				if s.Changed {
					state += "  CHANGED SINCE APPLIED"
				}
			}
			fmt.Printf("%%d  %%-40s %%s\n", s.Version, s.Name, state)
		}
		return nil
	case "seed":
		return %[10]s.Set.Run(ctx, db, args[1:]...)
	case "sql":
		pending, err := m.Pending(ctx)
		if err != nil {
			return err
		}
		for _, mg := range pending {
			stmts, err := m.SQL(mg, true)
			if err != nil {
				return err
			}
			fmt.Printf("-- %%d_%%s\n", mg.Version, mg.Name)
			for _, s := range stmts {
				fmt.Println(s + ";")
			}
		}
		return nil
	}
	return fmt.Errorf("unknown command %%q (use up, down [n], redo, status, sql, seed)", cmd)
}
`, d.Import, d.Name, d.Dialect, migPkg, d.DSNExample, cfg.Runner, libPath, lastSegment(cfg.Migrations),
		module+"/"+strings.TrimPrefix(cfg.Seeds, "./"), lastSegment(cfg.Seeds))
}

func lastSegment(p string) string {
	p = strings.TrimRight(p, "/")
	if i := strings.LastIndex(p, "/"); i >= 0 {
		return p[i+1:]
	}
	return p
}

func modelTmpl(pkg, name string, fields []FieldSpec, timestamps, softDelete bool) string {
	var b strings.Builder
	needTime := timestamps || softDelete
	for _, f := range fields {
		if strings.Contains(f.GoType(), "time.") {
			needTime = true
		}
	}
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	if needTime {
		b.WriteString("import \"time\"\n\n")
	}
	fmt.Fprintf(&b, "type %s struct {\n", name)
	b.WriteString("\tID int64 `db:\"id,primary\"`\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\t%s %s %s\n", f.GoName(), f.GoType(), f.Tag())
	}
	if timestamps {
		b.WriteString("\tCreatedAt time.Time `db:\"created_at\"`\n")
		b.WriteString("\tUpdatedAt time.Time `db:\"updated_at\"`\n")
	}
	if softDelete {
		b.WriteString("\tDeletedAt *time.Time `db:\"deleted_at\"`\n")
	}
	b.WriteString("}\n")
	return b.String()
}
