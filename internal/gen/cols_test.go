func TestRenderCols(t *testing.T) {
	src, err := renderCols("models", colsOutput{
		Imports: map[string]string{"time": "time", "github.com/google/uuid": "uuid", "example.com/x/v2": "x"},
		Models: []colsModel{
			{Name: "User", Table: "users", Fields: []colsField{
				{Name: "ID", Column: "id", Type: "uuid.UUID"},
				{Name: "Bio", Column: "bio", Type: "string", Nullable: true},
				{Name: "At", Column: "at", Type: "time.Time"},
				{Name: "X", Column: "x", Type: "x.Thing"},
			}},
			{Name: "Account", Table: "accounts", Fields: []colsField{{Name: "ID", Column: "id", Type: "int64"}}},
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	got := string(src)
	for _, want := range []string{
		"// Code generated by kiln gen. DO NOT EDIT.",
		"import (\n\t\"time\"\n\n\tx \"example.com/x/v2\"\n\t\"github.com/google/uuid\"\n\t\"github.com/mhdaslam790/kiln/q\"\n)",
		"var UserCols = userCols{",
		"\tBio q.Col[string] // nullable",
		"\tID  q.Col[uuid.UUID]",
		"ID: \"id\",",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in:\n%s", want, got)
		}
	}
	// Models are sorted, so output is stable.
	if strings.Index(got, "AccountCols") > strings.Index(got, "UserCols") {
		t.Error("models not sorted")
	}
}

// TestGenEndToEnd runs `kiln gen` for real: it builds the helper program
// against this repository, compiles the generated file and checks --check.
func TestGenEndToEnd(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go build")
	}
	p := linkedProject(t)
	must := func(err error) {
		t.Helper()
		if err != nil {
			t.Fatal(err)
		}
	}
	must(p.Init(Config{Dialect: "sqlite", Migrations: "db/migrations", Models: "models", Runner: "cmd/migrate", Seeds: "db/seeds"}, false))
	must(p.Create("User", []string{"email:string:unique", "age:int", "bio:text:null"}, CreateOptions{}))
	must(os.WriteFile(p.path("models", "status.go"), []byte("package models\n\ntype Status string\n"), 0o644))

	// A stale file referencing a type that no longer exists must not block
	// regeneration.
	must(os.WriteFile(p.path("models", ColsFile), []byte("package models\n\nvar _ Gone\n"), 0o644))
	must(p.Gen(GenOptions{}))
	got := read(t, p.path("models", ColsFile))
	for _, want := range []string{"Email     q.Col[string]", "Age       q.Col[int]", "Bio       q.Col[string] // nullable", "CreatedAt q.Col[time.Time]"} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in:\n%s", want, got)
		}
	}
	must(p.Gen(GenOptions{Check: true}))

	// The generated columns compile and type-check against q.Col.
	must(os.WriteFile(p.path("models", "use.go"), []byte(`package models

import "github.com/mhdaslam790/kiln/q"

var _ = []q.Filter{UserCols.Email.Eq("a"), UserCols.Age.Gte(18), UserCols.Bio.IsNull()}
`), 0o644))
	build := exec.Command("go", "build", "./models")
	build.Dir = p.Root
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("generated code does not build: %v\n%s", err, out)
	}

	// add-column refreshes the file; --check notices hand edits.
	must(p.AddColumns("User", []string{"score:int"}))
	if !strings.Contains(read(t, p.path("models", ColsFile)), "Score") {
		t.Error("add-column did not refresh " + ColsFile)
	}
	model := read(t, p.path("models", "user.go"))
	must(os.WriteFile(p.path("models", "user.go"), []byte(strings.Replace(model, "\tAge ", "\tNick string `db:\"nick\"`\n\tAge ", 1)), 0o644))
	if err := p.Gen(GenOptions{Check: true}); err == nil || !strings.Contains(err.Error(), "out of date") {
		t.Fatalf("--check after a hand edit: %v", err)
	}
}

// linkedProject is a temporary project whose go.mod points at this
// checkout of kiln, so generated helper programs build against it.
func linkedProject(t *testing.T) *Project {
	t.Helper()
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	p := newProject(t)
	goVersion := "1.23"
	if b, err := os.ReadFile(filepath.Join(root, "go.mod")); err == nil {
		for _, l := range strings.Split(string(b), "\n") {
			if v, ok := strings.CutPrefix(l, "go "); ok {
				goVersion = strings.TrimSpace(v)
			}
		}
	}
	gomod := "module example.com/app\n\ngo " + goVersion + "\n\nrequire github.com/mhdaslam790/kiln v1.0.0\n\nreplace github.com/mhdaslam790/kiln => " + root + "\n"
	if err := os.WriteFile(p.path("go.mod"), []byte(gomod), 0o644); err != nil {
		t.Fatal(err)
	}
	if sum, err := os.ReadFile(filepath.Join(root, "go.sum")); err == nil {
		if err := os.WriteFile(p.path("go.sum"), sum, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return p
}
